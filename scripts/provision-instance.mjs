#!/usr/bin/env node
// Provision a brand-new white-label instance (Option A): generate the bootstrap
// env values that must stay out of the database, write them to `.env.instance`,
// and print the one-time setup steps a fresh deployment needs.
//
// Usage:
//   node scripts/provision-instance.mjs                 # interactive
//   DATABASE_URL=postgres://... node scripts/provision-instance.mjs --env
//
// Values are generated locally and never leave this machine. Only
// DATABASE_URL, SETTINGS_ENCRYPTION_KEY, CRON_SECRET, AUTH_DEMO_MODE and
// SIMPLE_UI_ENABLED are env-level; everything else is configured from the UI.

import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import * as readline from 'node:readline/promises';
import { stdin, stdout } from 'node:process';

const hex = (bytes) => randomBytes(bytes).toString('hex');

async function main() {
  const args = process.argv.slice(2);
  const interactive = !args.includes('--env');

  const rl = interactive ? readline.createInterface({ input: stdin, output: stdout }) : null;

  const databaseUrl =
    process.env.DATABASE_URL ||
    (rl
      ? (await rl.question('Database URL (postgres://…): ')).trim()
      : '');

  const instanceName =
    process.env.INSTANCE_NAME ||
    (rl ? (await rl.question('Instance name (e.g. delhi-west, used as a comment): ')) || 'instance' : 'instance');

  if (rl) rl.close();
  if (!databaseUrl) {
    console.error('DATABASE_URL is required (pass it as an env var or answer the prompt).');
    process.exit(1);
  }

  const generated = {
    DATABASE_URL: databaseUrl,
    SETTINGS_ENCRYPTION_KEY: hex(32),
    CRON_SECRET: hex(24),
  };

  // Optional per-instance defaults. Can be omitted and set from the UI instead.
  if (process.env.WEBHOOK_SECRET) generated.WEBHOOK_SECRET = process.env.WEBHOOK_SECRET;
  if (process.env.SIMPLE_UI_ENABLED) generated.SIMPLE_UI_ENABLED = process.env.SIMPLE_UI_ENABLED;

  const lines = [
    `# ${instanceName} — generated by scripts/provision-instance.mjs`,
    '# Keep this file out of git (`.env*` is ignored).',
    '',
  ];
  for (const [k, v] of Object.entries(generated)) lines.push(`${k}=${v}`);
  const optional = ['EMAIL_FROM', 'EMAIL_FROM_NAME', 'APP_TIMEZONE', 'NEXT_PUBLIC_APP_URL'];
  for (const t of optional) {
    if (process.env[t]) lines.push(`${t}=${process.env[t]}`);
  }

  const outPath = resolve('.env.instance');
  writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');

  console.log(`\nWrote ${outPath}`);
  console.log("Copy it as your host's env (e.g. cp .env.instance .env.local) and run:");
  console.log('  1) npm run db:migrate              # create schema');
  console.log('  2) npm run db:ensure-admin -- <admin-email>   # first login');
  console.log('  3) npm start                       # boot the instance');
  console.log('\nThen configure the rest from the UI (Settings page):');
  console.log('  - Settings > Go-live checklist     # track status');
  console.log('  - Settings > Webhook secret        # protects POST /api/webhooks/leads');
  console.log('  - Settings > Timezone (IANA)       # digest/reminder scheduling');
  console.log('  - Settings > Email keys            # Resend API key + from address');
  console.log('  - Settings > Keys                  # Meta/Facebook page tokens');
  console.log('\nNever share or commit SETTINGS_ENCRYPTION_KEY: it is the master key for');
  console.log('every secret saved from the UI, and there is no UI way to view it again.\n');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});